"""Generates a runnable ADK agent that analyzes doubleml-pipeline results.

The agent covers one or more pipeline runs and is written to
`<output_dir>/agents/<agent_name>/`, so that `adk web <output_dir>/agents` lists
only agents. It bundles a copy of the skills it uses and refers to the runs by
paths relative to itself, so the results can be moved or shared together.
"""

import json
import os
import pathlib
import shutil
import string
from typing import Optional, Sequence, Union

from . import instruction
from . import results_reader

DEFAULT_AGENT_MODEL = "gemini-3.8-flash"
DEFAULT_AGENT_NAME = "causal_ml_insight_agent"
AGENTS_DIRNAME = "agents"
# Not resolve(): that would follow per-file symlinks out of the package.
BUNDLED_SKILLS_DIR = pathlib.Path(__file__).absolute().parent.parent / "skills"

_SKILL_FILE = "SKILL.md"

_INIT_PY = "from . import agent\n"

_AGENT_PY = string.Template('''\
"""ADK agent that extracts causal insights from doubleml-pipeline results.

Generated by doubleml_pipeline.agent.generate_agent(); edit freely.
Run it with `adk web` on the parent directory of this agent's folder.
"""

import pathlib

from doubleml_pipeline.agent import CausalResultsReader
from doubleml_pipeline.agent import INSTRUCTION
from google.adk import Agent
from google.adk.skills import load_skills_from_dir
from google.adk.tools.skill_toolset import SkillToolset

_AGENT_DIR = pathlib.Path(__file__).resolve().parent
_RUNS = {
$runs}

root_agent = Agent(
    name=$agent_name,
    model=$model,
    description=(
        "Explains the causal effects estimated by doubleml-pipeline and turns"
        " them into decision-ready insights."
    ),
    instruction=INSTRUCTION,
    tools=[
        *CausalResultsReader(_RUNS).tools(),
        SkillToolset(skills=load_skills_from_dir(_AGENT_DIR / "skills")),
    ],
)
''')

_ENV_EXAMPLE = """\
# Copy this file to .env in the same folder; ADK loads it automatically.
GOOGLE_GENAI_USE_VERTEXAI=TRUE
GOOGLE_CLOUD_PROJECT=your-project-id
GOOGLE_CLOUD_LOCATION=global
# To use a Gemini API key instead of Vertex AI:
# GOOGLE_GENAI_USE_VERTEXAI=FALSE
# GOOGLE_API_KEY=your-api-key
"""


PathLike = Union[str, "os.PathLike[str]"]


def generate_agent(
    results_dirs: Union[PathLike, Sequence[PathLike]],
    *,
    output_dir: Optional[PathLike] = None,
    run_names: Optional[Sequence[str]] = None,
    skills_dir: Optional[PathLike] = None,
    model: str = DEFAULT_AGENT_MODEL,
    agent_name: str = DEFAULT_AGENT_NAME,
) -> pathlib.Path:
  """Writes an ADK agent that analyzes the results of one or more runs.

  Regenerating overwrites the generated files and the copied skills.

  Args:
    results_dirs: The `output_dir` of a completed pipeline run, or a sequence of
      them, for example one run per channel.
    output_dir: Where to write `agents/<agent_name>/`. Defaults to the run's
      directory; required for several runs.
    run_names: Run names shown in answers, one per run. Default to the directory
      names.
    skills_dir: Directory whose subdirectories containing a SKILL.md are copied
      into the agent. Defaults to the skills bundled with the package.
    model: Gemini model the agent uses.
    agent_name: Agent name, also used as its folder name. Must be a valid Python
      identifier, as required by `adk web`.

  Returns:
    The generated agent directory.

  Raises:
    FileNotFoundError: If a run has no metadata.json or `skills_dir` does not
      exist.
    ValueError: If an argument is invalid, run names or treatment names are not
      unique, or `skills_dir` contains no skills or lies inside the agent.
  """
  if isinstance(results_dirs, (str, os.PathLike)):
    results_dirs = [results_dirs]
  runs_dirs = [pathlib.Path(d).resolve() for d in results_dirs]
  if not runs_dirs:
    raise ValueError("results_dirs must name at least one pipeline run.")
  if output_dir is None:
    if len(runs_dirs) > 1:
      raise ValueError("output_dir is required for several runs.")
    output_dir = runs_dirs[0]
  names = (
      list(run_names) if run_names is not None else [d.name for d in runs_dirs]
  )
  if len(names) != len(runs_dirs) or len(set(names)) != len(names):
    raise ValueError(f"Run names must be unique, one per run; got {names}.")
  # Fails early on missing metadata or treatments shared by several runs.
  results_reader.CausalResultsReader(dict(zip(names, runs_dirs)))
  if not agent_name.isidentifier():
    raise ValueError(
        f"agent_name must be a valid Python identifier, got {agent_name!r}."
    )
  if not model:
    raise ValueError("model must be a non-empty string.")
  skills_root = pathlib.Path(
      BUNDLED_SKILLS_DIR if skills_dir is None else skills_dir
  )
  if not skills_root.is_dir():
    raise FileNotFoundError(f"Skills directory {skills_root} does not exist.")
  skills = sorted(
      path for path in skills_root.iterdir() if (path / _SKILL_FILE).is_file()
  )
  if not skills:
    raise ValueError(f"No {_SKILL_FILE} found under {skills_root}.")

  agent_dir = pathlib.Path(output_dir).resolve() / AGENTS_DIRNAME / agent_name
  skills_copy = agent_dir / "skills"
  if skills_root.resolve().is_relative_to(skills_copy):
    raise ValueError(
        f"skills_dir {skills_root} is inside the generated agent, which is"
        " replaced on generation."
    )
  agent_dir.mkdir(parents=True, exist_ok=True)
  # json.dumps yields valid, escaped Python string literals.
  runs = "".join(
      "    {}: _AGENT_DIR / {},\n".format(
          json.dumps(name), json.dumps(_relative_posix(path, agent_dir))
      )
      for name, path in zip(names, runs_dirs)
  )
  (agent_dir / "__init__.py").write_text(_INIT_PY, encoding="utf-8")
  (agent_dir / "agent.py").write_text(
      _AGENT_PY.substitute(
          agent_name=json.dumps(agent_name),
          model=json.dumps(model),
          runs=runs,
      ),
      encoding="utf-8",
  )
  (agent_dir / ".env.example").write_text(_ENV_EXAMPLE, encoding="utf-8")

  if skills_copy.exists():
    shutil.rmtree(skills_copy)
  for skill in skills:
    _copy_contents(skill, skills_copy / skill.name)
  return agent_dir


def _relative_posix(path: pathlib.Path, start: pathlib.Path) -> str:
  """Returns `path` relative to `start`, with forward slashes."""
  return pathlib.Path(os.path.relpath(path, start)).as_posix()


def build_browser_system_instruction(
    skills_dir: Optional[PathLike] = None,
) -> str:
  """Builds the system instruction for the in-browser HTML report assistant."""
  skills_root = pathlib.Path(
      BUNDLED_SKILLS_DIR if skills_dir is None else skills_dir
  )
  parts = [instruction.INSTRUCTION.strip()]
  if skills_root.is_dir():
    for md_path in sorted(skills_root.rglob("*.md")):
      rel_name = md_path.relative_to(skills_root).as_posix()
      parts.append(
          f"--- Bundled Skill ({rel_name}) ---\n"
          + md_path.read_text(encoding="utf-8").strip()
      )
  parts.append(
      "Browser Report Mode\n"
      "- In this HTML report, all deterministic outputs from the"
      " CausalResultsReader tools ("
      + ", ".join(results_reader.TOOL_NAMES)
      + ") are already precomputed and provided in the"
      " causalAnalysisSnapshot JSON block.\n"
      "- Respond in English by default unless the user writes in another"
      " language."
  )
  return "\n\n".join(parts)


def _copy_contents(src: pathlib.Path, dst: pathlib.Path) -> None:
  """Copies a directory tree without its permissions.

  Package files can be read-only (for example in system site-packages); the
  generated copy must stay editable and removable on regeneration.

  Args:
    src: Directory to copy.
    dst: Destination directory, created as needed.
  """
  for path in src.rglob("*"):
    if path.is_file():
      target = dst / path.relative_to(src)
      target.parent.mkdir(parents=True, exist_ok=True)
      shutil.copyfile(path, target)
